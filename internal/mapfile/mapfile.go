// Package mapfile writes a generated map as a .h5m archive, from the base files embedded in base/.
//
// The base files come from the H5X map 00-test (map.xdb settings, the H5X secondary objective that
// advmap-manager.lua hooks, an empty map script) and from the vanilla map A1M3 (a player RandomTown with no
// specialization: its faction is the one chosen in the lobby). {{NAME}} placeholders are filled here.
package mapfile

import (
	"archive/zip"
	"bytes"
	"embed"
	"fmt"
	"math/rand"
	"strings"
	"unicode/utf16"

	"h5mapgen/internal/generate"
	"h5mapgen/internal/layout"
)

//go:embed base
var base embed.FS

// LayoutFile is the copy of the layout kept in the map folder, so a generated map can be reopened.
const LayoutFile = "layout.h5mapgen.json"

// Description is the description text of generated maps.
const Description = "Generated by h5-mapgen"

var rotations = [4]string{"0", "1.5708", "3.14159", "4.71239"}

func baseFile(name string) string {
	data, err := base.ReadFile("base/" + name)
	if err != nil {
		panic(err) // embedded, can't be missing
	}
	return string(data)
}

func fill(text string, values map[string]string) string {
	for k, v := range values {
		text = strings.ReplaceAll(text, "{{"+k+"}}", v)
	}
	if i := strings.Index(text, "{{"); i >= 0 {
		panic("unfilled placeholder " + text[i:min(len(text), i+30)])
	}
	return text
}

// utf16Text encodes a game text: UTF-16 LE with a byte order mark.
func utf16Text(s string) []byte {
	out := []byte{0xFF, 0xFE}
	for _, c := range utf16.Encode([]rune(s)) {
		out = append(out, byte(c), byte(c>>8))
	}
	return out
}

func guid(rnd *rand.Rand) string {
	b := make([]byte, 16)
	rnd.Read(b)
	return fmt.Sprintf("%X-%X-%X-%X-%X", b[0:4], b[4:6], b[6:8], b[8:10], b[10:16])
}

// Folder is the map folder inside the archive. Two maps must never share one.
func Folder(l *layout.Layout) string {
	return "Maps/Multiplayer/" + strings.ReplaceAll(l.Name, " ", "_") + "/"
}

// Build writes the .h5m archive of a generated map.
func Build(l *layout.Layout, res *generate.Result) ([]byte, error) {
	const nl = "\r\n"
	size := fmt.Sprint(l.Size)

	townIDs := map[int]string{}
	var objects []string
	for _, t := range res.Towns {
		id := "item_" + guid(res.Rand)
		townIDs[t.Player] = id
		objects = append(objects, fill(baseFile("town.xml"), map[string]string{
			"ID": id, "X": fmt.Sprint(t.X), "Y": fmt.Sprint(t.Y), "ROT": rotations[t.Turns&3],
			"PLAYER": fmt.Sprintf("PLAYER_%d", t.Player),
		}))
	}
	var players []string
	for p := 1; p <= layout.MaxPlayers; p++ {
		mainTown, active := "<MainTown/>", p <= len(l.Starts)
		if id, ok := townIDs[p]; ok {
			mainTown = fmt.Sprintf(`<MainTown href="#xpointer(id(%s)/AdvMapTown)"/>`, id)
		}
		players = append(players, fill(baseFile("player.xml"), map[string]string{
			"MAIN_TOWN": mainTown, "ACTIVE": fmt.Sprint(active), "TEAM": "0", "HERO_IN_TOWN": fmt.Sprint(active),
		}))
	}
	tiles := "<tiles/>"
	if len(res.Tiles) > 0 {
		tiles = "<tiles>" + nl
		for _, href := range res.Tiles {
			tiles += "\t\t<Item href=\"" + href + "\"/>" + nl
		}
		tiles += "\t</tiles>"
	}
	objectsXML := "<objects/>"
	if len(objects) > 0 {
		objectsXML = "<objects>" + nl + strings.Join(objects, nl) + nl + "\t</objects>"
	}
	mapXdb := fill(baseFile("map.xdb"), map[string]string{
		"SIZE": size, "OBJECTS": objectsXML, "TILES": tiles, "PLAYERS": strings.Join(players, nl),
	})
	teams := "<teams>" + nl + strings.Repeat("\t\t<Item>1</Item>"+nl, len(l.Starts)) + "\t</teams>"
	mapTag := fill(baseFile("map-tag.xdb"), map[string]string{"SIZE": size, "TEAMS": teams})

	files := []struct {
		name string
		data []byte
	}{
		{"map-tag.xdb", []byte(mapTag)},
		{"map.xdb", []byte(mapXdb)},
		{"GroundTerrain.bin", res.Terrain.Bytes()},
		{"name.txt", utf16Text(l.Name)},
		{"description.txt", utf16Text(Description)},
		{"Rumour.txt", utf16Text("")},
		{LayoutFile, l.JSON()},
	}
	for _, f := range []string{"H5X_MapScript.xdb", "MapGoalText.txt", "objective-caption-text.txt", "objective-desc-text.txt"} {
		files = append(files, struct {
			name string
			data []byte
		}{f, []byte(baseFile(f))})
	}
	for i := 0; i < layout.MaxPlayers; i++ {
		suffix := ""
		if i > 0 {
			suffix = fmt.Sprintf(".%d", i)
		}
		files = append(files,
			struct {
				name string
				data []byte
			}{"scenario-caption" + suffix + ".txt", utf16Text(l.Name)},
			struct {
				name string
				data []byte
			}{"scenario-description" + suffix + ".txt", utf16Text(Description)})
	}

	var buf bytes.Buffer
	w := zip.NewWriter(&buf)
	folder := Folder(l)
	for _, f := range files {
		out, err := w.Create(folder + f.name)
		if err != nil {
			return nil, err
		}
		if _, err := out.Write(f.data); err != nil {
			return nil, err
		}
	}
	if err := w.Close(); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}
